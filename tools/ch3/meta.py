import math, random

def blob(cx, cy, rx, ry, n=10, seed=1, jitter=0.1):
    rnd = random.Random(seed)
    pts = []
    for i in range(n):
        a = 2 * math.pi * i / n
        k = 1 + rnd.uniform(-jitter, jitter)
        pts.append("%d,%d" % (round(cx + rx * k * math.cos(a)), round(cy + ry * k * math.sin(a))))
    return " ".join(pts)

